using System.Text;
using System.Linq;
using System.Collections.Generic;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System.Text.RegularExpressions;

namespace Faster.Modulith.Generators
{
    /// <summary>
    /// Generates host extension methods for registering referenced modules
    /// into the dependency injection container.
    /// </summary>
    /// <remarks>
    /// This generator scans referenced assemblies and:
    /// 
    /// - Detects assemblies that follow the "Module.*" naming convention
    /// - Generates Add{ModuleName} extension methods
    /// - Automatically binds configuration sections
    /// - Registers module infrastructure
    ///
    /// It does NOT execute for module projects themselves.
    /// </remarks>
    [Generator]
    public class OptionsGenerator : IIncrementalGenerator
    {
        /// <summary>
        /// Configures the incremental generator pipeline.
        /// </summary>
        /// <param name="context">
        /// The incremental generator initialization context.
        /// </param>
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var compilation = context.CompilationProvider;

            context.RegisterSourceOutput(compilation, (spc, comp) =>
            {
                // ---------------------------------------------------------
                // GUARD 1: IGNORE MODULE PROJECTS
                // ---------------------------------------------------------
                if (comp.AssemblyName.StartsWith("Module."))
                {
                    return;
                }

                // ---------------------------------------------------------
                // SCAN REFERENCED ASSEMBLIES
                // ---------------------------------------------------------

                var log = new StringBuilder();
                log.AppendLine("// <auto-generated/>");
                log.AppendLine($"// Generator Run on: {comp.AssemblyName}");

                var modules = new List<ModuleInfo>();

                foreach (var assembly in comp.SourceModule.ReferencedAssemblySymbols)
                {
                    var name = assembly.Name;

                    // 1. FILTER: Ignore support libraries
                    if (name.EndsWith(".Api") ||
                        name.EndsWith(".Contracts") ||
                        name.EndsWith(".Tests"))
                        continue;

                    // 2. CHECK: Must follow module naming pattern
                    bool isMatch =
                        name.StartsWith("Module.") ||
                        name.Contains(".Module") ||
                        name.EndsWith(".Module");

                    if (!isMatch)
                        continue;

                    // 3. EXTRACT SIMPLE MODULE NAME
                    var match = Regex.Match(name, @"\.Modules?\.(\w+)", RegexOptions.IgnoreCase);
                    var simpleName = match.Success
                        ? match.Groups[1].Value
                        : name.Split('.').Last();

                    // Edge case: avoid returning "Module" as module name
                    if (simpleName.Equals("Module", System.StringComparison.OrdinalIgnoreCase))
                    {
                        var parts = name.Split('.');
                        if (parts.Length > 1)
                            simpleName = parts[parts.Length - 2];
                    }

                    modules.Add(new ModuleInfo
                    {
                        Namespace = name + ".Infrastructure",
                        Name = simpleName
                    });
                }

                // ---------------------------------------------------------
                // GUARD 2: IF NO MODULES FOUND, STOP
                // ---------------------------------------------------------
                if (modules.Count == 0)
                    return;

                // ---------------------------------------------------------
                // CODE GENERATION
                // ---------------------------------------------------------

                var sb = new StringBuilder();
                sb.Append(log.ToString());

                sb.AppendLine("using System;");
                sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
                sb.AppendLine("using Microsoft.Extensions.Configuration;");
                sb.AppendLine("using Faster.Modulith.Contracts;");
                sb.AppendLine("using Faster.Modulith;");

                // Include infrastructure namespaces for each module
                foreach (var mod in modules)
                {
                    sb.AppendLine($"using {mod.Namespace};");
                }

                sb.AppendLine(@"
namespace Faster.Modulith
{
    /// <summary>
    /// Extension methods for configuring the Faster.Modulith host.
    /// </summary>
    public static partial class FasterModulithHostExtensions
    {
        /// <summary>
        /// Registers the modulith core services.
        /// </summary>
        /// <param name=""services"">Service collection.</param>
        /// <param name=""configuration"">Application configuration.</param>
        /// <param name=""configure"">Optional configuration callback.</param>
        /// <returns>The updated service collection.</returns>
        public static IServiceCollection AddModulith(
            this IServiceCollection services, 
            IConfiguration configuration,
            Action<FasterModulithOptions> configure)
        {
            services.AddScoped<IOrchestrator, Orchestrator>();

            var options = new FasterModulithOptions(services, configuration);
            configure?.Invoke(options);

            return services;
        }
");

                // ---------------------------------------------------------
                // MODULE REGISTRATION METHODS
                // ---------------------------------------------------------

                foreach (var mod in modules)
                {
                    sb.AppendLine($@"
        /// <summary>
        /// Registers the {mod.Name} module.
        /// </summary>
        /// <param name=""options"">The modulith options builder.</param>
        /// <param name=""configure"">
        /// Optional configuration delegate for {mod.Name}Options.
        /// </param>
        /// <returns>The updated modulith options.</returns>
        public static FasterModulithOptions Add{mod.Name}(
            this FasterModulithOptions options, 
            Action<{mod.Name}Options> configure = null)
        {{
            // 1. Automatic configuration binding
            options.Services.Configure<{mod.Name}Options>(
                options.Configuration.GetSection(""{mod.Name}""));

            // 2. Infrastructure registration
            options.Services.Add{mod.Name}Module(configure);
            
            return options;
        }}");
                }

                sb.AppendLine(@"
    }
}");

                spc.AddSource(
                    "FasterModulithHostExtensions.g.cs",
                    SourceText.From(sb.ToString(), Encoding.UTF8));
            });
        }

        /// <summary>
        /// Internal metadata holder for discovered modules.
        /// </summary>
        private class ModuleInfo
        {
            /// <summary>
            /// Infrastructure namespace of the module.
            /// </summary>
            public string Namespace { get; set; }

            /// <summary>
            /// Simple module name (e.g. Kitchen, Orders).
            /// </summary>
            public string Name { get; set; }
        }
    }
}
